fn fade(stage: &mut Stage<'_>, mobs: &[Mob], incoming: bool) -> fmn::Result<()> {
    let mut anims: Vec<Box<dyn Animation>> = Vec::new();
    for &m in mobs {
        let a = if incoming {
            fade_in(stage.arena_mut(), m, ORIGIN, 1.0)?
        } else {
            fade_out(stage.arena_mut(), m, ORIGIN, 1.0)?
        };
        anims.push(stage.prepare(a.rt(0.4))?);
    }
    stage.play_prepared(anims)?;
    Ok(())
}

// ---- the arithmetic the pictures draw ------------------------------------------

/// The clock and the move of 10_1 to 10_6.
pub(crate) const N: i32 = 12;
pub(crate) const K: i32 = 8;

/// The positions `start`, `start + k`, ... on the `n`-clock, in visiting
/// order, up to (not including) the first return to `start`.
pub(crate) fn walk(n: i32, k: i32, start: i32) -> Vec<i32> {
    let first = start.rem_euclid(n);
    let mut out = vec![first];
    loop {
        let next = (out[out.len() - 1] + k).rem_euclid(n);
        if next == first {
            return out;
        }
        out.push(next);
    }
}

/// The first positive number of `+k` moves whose total is a whole number of
/// laps of the `n`-clock.
pub(crate) fn order(n: i32, k: i32) -> i32 {
    let mut m = 1;
    while (m * k).rem_euclid(n) != 0 {
        m += 1;
    }
    m
}

/// The `n`-clock split into the orbits of `+k`: a walk from each position
/// that no earlier walk reached.
pub(crate) fn orbits(n: i32, k: i32) -> Vec<Vec<i32>> {
    let mut out: Vec<Vec<i32>> = Vec::new();
    for start in 0..n {
        if !out.iter().any(|orbit| orbit.contains(&start)) {
            out.push(walk(n, k, start));
        }
    }
    out
}

/// The largest number dividing both, found by trying every candidate.
pub(crate) fn common_divisor(a: i32, b: i32) -> i32 {
    (1..=a.max(b)).rev().find(|d| a % d == 0 && b % d == 0).unwrap_or(1)
}

/// The moves whose walk from 0 visits every position of the `n`-clock.
pub(crate) fn generators(n: i32) -> Vec<i32> {
    (1..n).filter(|&k| order(n, k) == n).collect()
}

/// 10_7 to 10_9: g is the move +1 on the twelve-clock, so g^m sits at m
/// modulo 12, and H is the subgroup generated by 8 in 10_2.
pub(crate) fn h_members() -> Vec<i32> {
    let mut members = walk(N, K, 0);
    members.sort_unstable();
    members
}
pub(crate) fn in_h(m: i32) -> bool {
    h_members().contains(&m.rem_euclid(N))
}
/// The smallest positive exponent whose power lies in H.
pub(crate) fn least_step() -> i32 {
    (1..=N).find(|&j| in_h(j)).unwrap_or(N)
}
/// `m = q d + r` with `0 <= r < d`.
pub(crate) fn split(m: i32, d: i32) -> (i32, i32) {
    (m.div_euclid(d), m.rem_euclid(d))
}
