fn at_hour(center: (f64, f64), radius: f64, hour: f64) -> Vec3 {
    let a = FRAC_PI_2 - TAU * hour / 12.0;
    v(center.0 + radius * a.cos(), center.1 + radius * a.sin())
}

fn position(hour: i32, radius: f64) -> Vec3 {
    at_hour(CLOCK, radius, f64::from(hour.rem_euclid(12)))
}

fn line_x(m: i32) -> f64 {
    -1.0 + 0.55 * f64::from(m)
}

fn grid_x(k: i32) -> f64 {
    -4.0 + 0.9 * f64::from(k - 1)
}

fn orbit_color(i: usize) -> Srgb {
    [Palette::gold(), Palette::blue(), Palette::green(), Palette::purple()][i % 4]
}

