"""Measure what the frames and the scratch cue table say about chapter 17.

Run from the repo root: python3 -I -B <this file>
Reads only; prints to stdout. Three measurements, none of them a viewing:

1. Frame byte identity. Consecutive sampled PNGs with the same sha256 are the same
   picture. A change of hash is not proof of a visible change, because the preview
   is a lossy encode (CRF 26), so the runs below are lower bounds on a hold.
2. Sentence starts by share of characters, which is how a scratch voice line is
   paced by the kit. They are estimates for the SCRATCH voice only, not Oliver.
3. Independent arithmetic for every number the chapter shows.
"""
import hashlib
import json
from pathlib import Path

F = Path("narration_lab/third-wave-20261024/root/five-film-release-20261027")
FRAMES = F / "algebra-combined-repair-frames01/17_applications"
CUES = F / "algebra-combined-repair-preview01/render/17_applications.cues.tsv"
SCRIPT = Path("explainer_corpus/abstract_algebra_expanded/script.tsv")

sampling = json.loads((FRAMES / "sampling.json").read_text())
times = sampling["times"] if "times" in sampling else sampling["samples"]
times = [t["time"] if isinstance(t, dict) else t for t in times]
pngs = sorted(FRAMES.glob("frame-*.png"))
print(f"{len(pngs)} frames, {len(times)} sampled times")
assert len(pngs) == len(times)

hashes = [hashlib.sha256(p.read_bytes()).hexdigest() for p in pngs]
print("\n# runs of at least 10 s with byte-identical frames")
start = 0
for i in range(1, len(hashes) + 1):
    if i == len(hashes) or hashes[i] != hashes[start]:
        if times[i - 1] - times[start] >= 10:
            print(f"frames {start:04d}-{i - 1:04d}  {times[start]:8.3f} to {times[i - 1]:8.3f}  {times[i - 1] - times[start]:6.2f} s")
        start = i

lines = {}
for raw in SCRIPT.read_text(encoding="utf-8").splitlines():
    if raw and not raw.startswith("#"):
        cue, text = raw.split("\t", 1)
        lines[cue] = text


def sentences(text):
    out, start = [], 0
    for i, c in enumerate(text):
        if c in ".?!" and (i + 1 == len(text) or text[i + 1] == " "):
            out.append(text[start : i + 1].strip())
            start = i + 1
    return out


cue_rows = []
for raw in CUES.read_text(encoding="utf-8").splitlines():
    parts = raw.split("\t")
    if parts and parts[0].startswith("17_"):
        cue_rows.append((parts[0], float(parts[1]), float(parts[2])))
print(f"\n# {len(cue_rows)} cues; sentence starts by share of characters (scratch estimate)")
for cue, start, length in cue_rows:
    said = sentences(lines[cue])
    total = sum(len(s) for s in said)
    at = 0
    print(f"{cue}  {start:.3f} + {length:.3f}")
    for j, s in enumerate(said):
        print(f"   {j}  {start + length * at / total:8.3f}  {s[:64]}")
        at += len(s)

print("\n# arithmetic")
D = [0, 3, 0, 6, 4, 0, 6, 1, 5, 2]
W = list(range(10, 0, -1))
P = [d * w for d, w in zip(D, W)]
print("products", P, "sum", sum(P), "mod 11", sum(P) % 11)
assert P == [0, 27, 0, 42, 24, 0, 24, 3, 10, 2] and sum(P) == 132 == 12 * 11
print("running", [sum(P[: i + 1]) for i in range(10)])
assert (132 + 7) % 11 == 7
print("7d mod 11", [7 * d % 11 for d in range(1, 11)])
assert sorted(7 * d % 11 for d in range(1, 11)) == list(range(1, 11))
assert 2 * 3 % 6 == 0
assert 7 * 6 + 6 * 4 == 66 and 7 * 4 + 6 * 6 == 64 and (7 - 6) * (4 - 6) == -2
assert 132 + 10 == 142 and 142 + 45 == 187 == 17 * 11 and 45 == 4 * 11 + 1 and 10 + 45 == 55


def syndrome(word):
    s = 0
    for i, c in enumerate(word, 1):
        if c == "1":
            s ^= i
    return s


def flip(word, *positions):
    w = list(word)
    for p in positions:
        w[p - 1] = "1" if w[p - 1] == "0" else "0"
    return "".join(w)


SENT = "0110011"
assert syndrome(SENT) == 0
one = flip(SENT, 5)
assert one == "0110111" and syndrome(one) == 5
assert [i for i, c in enumerate(one, 1) if c == "1"] == [2, 3, 5, 6, 7]
two = flip(SENT, 2, 5)
assert two == "0010111" and syndrome(two) == 7
assert [i for i, c in enumerate(two, 1) if c == "1"] == [3, 5, 6, 7]
wrong = flip(two, 7)
assert wrong == "0010110" and syndrome(wrong) == 0
xor = "".join(str(int(a) ^ int(b)) for a, b in zip(SENT, "1110000"))
assert xor == "1000011" and syndrome(xor) == 0 and syndrome("1110000") == 0
code = [f"{n:07b}" for n in range(128) if syndrome(f"{n:07b}") == 0]
assert len(code) == 16 and 128 // 16 == 8
assert len({syndrome(flip(SENT, p)) for p in range(1, 8)} | {0}) == 8
print("parity of the sent word:", SENT.count("1") % 2, "; received two-flip word ones:", two.count("1"), "; decoded wrong word ones:", wrong.count("1"))
print("cosets of {0,4,8} in Z12:", [sorted((c + h) % 12 for h in (0, 4, 8)) for c in range(4)])
print("generated by 6 in Z12:", sorted({6 * k % 12 for k in range(12)}))
print("ARITHMETIC OK")
