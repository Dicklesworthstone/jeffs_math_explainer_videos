//! The governed-closure CI gate (D1, fm-g2c): the real workspace lock
//! must audit clean against the committed allowlist, SUITE.lock must
//! parse and agree with the pinned toolchain, and an injected unlisted
//! package must be caught (the negative test the bead demands).

use std::{fs::File, io::Read};

use fmn_conformance::closure::{
    AllowRow, LockedPackage, Violation, audit, audit_with_aux, parse_allowlist, parse_cargo_lock,
};
use fmn_hash::sha256;

const MAX_AUTHORITY_BYTES: u64 = 8 * 1024 * 1024;
const LOCK_PREAMBLE: &str = "# This file is automatically @generated by Cargo.\n\
# It is not intended for manual editing.\n\
version = 4\n\n";

fn read_utf8_bounded(reader: impl Read, label: &str, max_bytes: u64) -> Result<String, String> {
    let mut bytes = Vec::new();
    reader
        .take(max_bytes.saturating_add(1))
        .read_to_end(&mut bytes)
        .map_err(|error| format!("reading {label}: {error}"))?;
    if u64::try_from(bytes.len()).unwrap_or(u64::MAX) > max_bytes {
        return Err(format!(
            "reading {label}: file exceeds the {max_bytes}-byte resource limit"
        ));
    }
    String::from_utf8(bytes).map_err(|error| format!("reading {label}: not UTF-8: {error}"))
}

fn repo_file(name: &str) -> String {
    let path = format!("{}/../../{name}", env!("CARGO_MANIFEST_DIR"));
    // The panic!/unreachable! macros are off-limits repo-wide (UBS); a
    // missing governed file must still fail the test loudly, with context.
    let file = File::open(&path)
        .unwrap_or_else(|error| std::panic::panic_any(format!("opening {path}: {error}")));
    read_utf8_bounded(file, &path, MAX_AUTHORITY_BYTES)
        .unwrap_or_else(|error| std::panic::panic_any(error))
}

fn lock_document(package_blocks: &str) -> String {
    let mut document = String::from(LOCK_PREAMBLE);
    document.push_str(package_blocks);
    if !document.ends_with('\n') {
        document.push('\n');
    }
    document
}

fn must_parse_lock(text: &str) -> Vec<LockedPackage> {
    parse_cargo_lock(text)
        .unwrap_or_else(|error| std::panic::panic_any(format!("valid Cargo.lock: {error}")))
}

fn must_parse_allowlist(text: &str) -> Vec<AllowRow> {
    parse_allowlist(text).unwrap_or_else(|error| {
        std::panic::panic_any(format!("valid SUITE_ALLOWLIST.tsv: {error}"))
    })
}

/// Committed lockfiles of governed NON-member crates (ADR-0003: the fuzz
/// harness, non-member spikes). Their packages carry class=dev/fuzz rows;
/// the audit walks each lock that exists.
const AUX_LOCKS: &[&str] = &[
    "spikes/g0-5-python-ext/Cargo.lock",
    "spikes/g0-8-accelerator/Cargo.lock",
    "fuzz/Cargo.lock",
    // W5 wasm tier 1 (fm-l97): the headless smoke probe's independent lock.
    // Its universe is a subset of the governed closure; the row set above
    // admits it exactly like the spike locks.
    "wasm-smoke/Cargo.lock",
];

#[test]
fn authority_reader_checks_limit_before_text_validation() {
    let oversized_invalid = std::io::Cursor::new(vec![0xff_u8; 9]);
    let result = read_utf8_bounded(oversized_invalid, "synthetic authority", 8);
    assert!(
        matches!(&result, Err(error) if error.contains("exceeds the 8-byte resource limit") && !error.contains("UTF-8")),
        "oversized input was not rejected before text validation: {result:?}"
    );

    assert_eq!(
        read_utf8_bounded(std::io::Cursor::new(b"12345678"), "exact authority", 8),
        Ok("12345678".to_owned()),
        "an authority exactly at the byte limit must remain readable"
    );
}

#[test]
fn workspace_closure_is_exactly_the_governed_universe() {
    let lock = must_parse_lock(&repo_file("Cargo.lock"));
    assert!(
        lock.len() >= 20,
        "lock parser found only {} packages — parser or lock broken",
        lock.len()
    );
    let allowlist = must_parse_allowlist(&repo_file("SUITE_ALLOWLIST.tsv"));
    let aux: Vec<_> = AUX_LOCKS
        .iter()
        .map(|name| {
            let text = repo_file(name);
            must_parse_lock(&text)
        })
        .collect();
    assert_eq!(aux.len(), AUX_LOCKS.len(), "every governed lock must parse");
    let violations = audit_with_aux(&lock, &aux, &allowlist);
    assert!(
        violations.is_empty(),
        "governed-closure violations:\n{}",
        violations
            .iter()
            .map(ToString::to_string)
            .collect::<Vec<_>>()
            .join("\n")
    );
}

#[test]
fn wasm_audit_is_bound_to_current_locks() {
    let audit = repo_file("docs/wasm_audit.md");
    for authority in ["SUITE.lock", "Cargo.lock"] {
        let document = repo_file(authority);
        let digest = sha256(document.as_bytes()).to_hex();
        let marker = format!("- `{authority}` SHA-256: `{digest}`");
        assert!(
            audit.lines().any(|line| line == marker),
            "docs/wasm_audit.md is stale: expected the current lock identity `{marker}`; re-run the fm-7wm.4 wasm target, tree, Node, and affected browser gates before updating the audit"
        );
    }
}

#[test]
fn cargo_lock_parser_rejects_malformed_or_ambiguous_records() {
    let cases = [
        lock_document("[[package]]\nname = \"missing-version\"\n"),
        lock_document("[[package]]\nname = \"repeated\"\nname = \"again\"\nversion = \"1.0.0\"\n"),
        lock_document("[[package]]\nname = \"unknown\"\nversion = \"1.0.0\"\nmagic = \"hidden\"\n"),
        lock_document(
            "[[package]]\nname = \"unterminated\"\nversion = \"1.0.0\"\ndependencies = [\n \"dep\",\n",
        ),
        lock_document(
            "[[package]]\nname = \"duplicate\"\nversion = \"1.0.0\"\n\n\
             [[package]]\nname = \"duplicate\"\nversion = \"1.0.0\"\n",
        ),
    ];
    for case in cases {
        assert!(
            parse_cargo_lock(&case).is_err(),
            "malformed lockfile was accepted: {case:?}"
        );
    }
}

