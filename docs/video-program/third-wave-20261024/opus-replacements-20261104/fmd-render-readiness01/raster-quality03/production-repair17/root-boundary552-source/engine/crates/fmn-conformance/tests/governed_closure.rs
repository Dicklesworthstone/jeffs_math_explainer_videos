#[test]
fn allowlist_parser_preserves_consistent_multi_context_rows() {
    let rows = must_parse_allowlist(
        "wasm-bindgen\t0.2.126\tcrates-io\taaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\tdefault\tMIT/Apache-2.0\tno\tyes\tno\tno\texpansion\truntime\twasm surface\tfm\tdeliberate\n\
         wasm-bindgen\t0.2.126\tcrates-io\taaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\tdefault,std\tMIT OR Apache-2.0\tyes\tno\tno\tno\texpansion\tdev\tscheduler harness\tfm\twith-pin\n",
    );
    assert_eq!(rows.len(), 2);
    assert_eq!(rows[0].checksum, rows[1].checksum);
    assert_ne!(rows[0].class, rows[1].class);
}

#[test]
fn governed_parsers_enforce_canonical_encoding_and_line_bounds() {
    let mut no_final_newline =
        lock_document("[[package]]\nname = \"no-newline\"\nversion = \"1.0.0\"\n");
    assert_eq!(no_final_newline.pop(), Some('\n'));
    assert!(parse_cargo_lock(&no_final_newline).is_err());

    let crlf =
        lock_document("[[package]]\nname = \"crlf\"\nversion = \"1.0.0\"\n").replace('\n', "\r\n");
    assert!(parse_cargo_lock(&crlf).is_err());

    let oversized_line = format!("#{}\n", "x".repeat(16 * 1024 + 1));
    assert!(parse_allowlist(&oversized_line).is_err());
}

#[test]
fn injected_unlisted_package_is_caught() {
    // The negative test: a package smuggled into the lock must fail loud.
    let mut lock_text = repo_file("Cargo.lock");
    lock_text.push_str(
        "\n[[package]]\nname = \"smuggled-dep\"\nversion = \"1.2.3\"\n\
         source = \"registry+https://github.com/rust-lang/crates.io-index\"\n\
         checksum = \"deadbeefdeadbeefdeadbeefdeadbeefdeadbeefdeadbeefdeadbeefdeadbeef\"\n",
    );
    let lock = must_parse_lock(&lock_text);
    let allowlist = must_parse_allowlist(&repo_file("SUITE_ALLOWLIST.tsv"));
    let violations = audit(&lock, &allowlist);
    assert!(
        violations.iter().any(|v| matches!(
            v,
            Violation::Unlisted { name, .. } if name == "smuggled-dep"
        )),
        "the smuggled package was not flagged: {violations:?}"
    );
}

#[test]
fn a_listed_package_at_an_unlisted_version_is_still_caught() {
    // ADR-0008 keys rows by (name, version) so independently-resolved spike
    // locks can carry different majors of a shared build-time dependency. The
    // loosening it must NOT introduce: a package sliding to an unreviewed
    // version because some other version of the same name happens to be listed.
    let lock_text = lock_document(
        "[[package]]\nname = \"syn\"\nversion = \"9.9.9\"\n\
         source = \"registry+https://github.com/rust-lang/crates.io-index\"\n\
         checksum = \"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\"\n",
    );
    let lock = must_parse_lock(&lock_text);
    let allowlist = must_parse_allowlist(
        "syn\t2.0.119\tcrates-io\taaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\t-\tMIT\tno\tno\tno\tno\tforbid\tdev\treason\tfm\tw\n",
    );
    let violations = audit(&lock, &allowlist);
    assert!(
        violations
            .iter()
            .any(|v| matches!(v, Violation::Unlisted { name, version } if name == "syn" && version == "9.9.9")),
        "an unreviewed version slipped through: {violations:?}"
    );
}

#[test]
fn two_versions_of_one_package_are_admitted_when_both_are_listed() {
    // The other half of ADR-0008, and the case that actually occurs: the G0-5
    // spike's PyO3 graph pins `syn 2`, the G0-8 spike's Metal graph pins
    // `syn 3`, both are non-shipped, both are reviewed.
    let a_text = lock_document(
        "[[package]]\nname = \"syn\"\nversion = \"2.0.119\"\n\
         source = \"registry+https://github.com/rust-lang/crates.io-index\"\n\
         checksum = \"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\"\n",
    );
    let b_text = lock_document(
        "[[package]]\nname = \"syn\"\nversion = \"3.0.3\"\n\
         source = \"registry+https://github.com/rust-lang/crates.io-index\"\n\
         checksum = \"bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb\"\n",
    );
    let a = must_parse_lock(&a_text);
    let b = must_parse_lock(&b_text);
    let allowlist = must_parse_allowlist(
        "syn\t2.0.119\tcrates-io\taaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\t-\tMIT\tno\tno\tno\tno\tforbid\tdev\treason\tfm\tw\n\
         syn\t3.0.3\tcrates-io\tbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb\t-\tMIT\tno\tno\tno\tno\tforbid\tdev\treason\tfm\tw\n",
    );
    assert!(audit_with_aux(&a, &[b], &allowlist).is_empty());
}

#[test]
fn checksum_drift_is_caught() {
    let lock_text = lock_document(
        "[[package]]\nname = \"pyo3\"\nversion = \"0.23.0\"\n\
         source = \"registry+https://github.com/rust-lang/crates.io-index\"\n\
         checksum = \"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\"\n",
    );
    let lock = must_parse_lock(&lock_text);
    // A consumed row with a pinned checksum that differs must flag.
    let allowlist = must_parse_allowlist(
        "pyo3\t0.23.0\tcrates-io\tbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb\tx\tMIT\tyes\tyes\tpython\tno\texpansion\tffi\treason\tfm\tpolicy\n",
    );
    let violations = audit(&lock, &allowlist);
    assert!(
        violations
            .iter()
            .any(|v| matches!(v, Violation::ChecksumMismatch { name, .. } if name == "pyo3")),
        "checksum drift not flagged: {violations:?}"
    );
    // TBD checksums (pending rows) do not flag — consumption fills them.
    let pending = must_parse_allowlist(
        "pyo3\t0.23.0\tcrates-io\tTBD\tx\tMIT\tyes\tyes\tpython\tno\texpansion\tpending\treason\tfm\tpolicy\n",
    );
    assert!(audit(&lock, &pending).is_empty());
}

#[test]
fn source_drift_in_an_auxiliary_lock_is_caught() {
    let admitted_text = lock_document(
        "[[package]]\nname = \"suite-crate\"\nversion = \"1.0.0\"\n\
         source = \"git+https://github.com/example/expected?rev=1111111111111111111111111111111111111111#1111111111111111111111111111111111111111\"\n",
    );
    let drifted_text = lock_document(
        "[[package]]\nname = \"suite-crate\"\nversion = \"1.0.0\"\n\
         source = \"git+https://github.com/example/different?rev=2222222222222222222222222222222222222222#2222222222222222222222222222222222222222\"\n",
    );
    let admitted = must_parse_lock(&admitted_text);
    let drifted = must_parse_lock(&drifted_text);
    let allowlist = must_parse_allowlist(
        "suite-crate\t1.0.0\tgit+expected@SUITE.lock\t-\t-\tMIT\tno\tno\tno\tno\tforbid\tdev\treason\tfm\twith-pin\n",
    );
    let violations = audit_with_aux(&admitted, &[drifted], &allowlist);
    assert!(
        violations
            .iter()
            .any(|violation| matches!(violation, Violation::SourceMismatch { name, .. } if name == "suite-crate")),
        "source drift in a second lock was not flagged: {violations:?}"
    );
}

