body = [head]
for name in KEEP_CONSTANTS:
    body.append(consts[name])
body.append(stubs)
for name in KEEP_FUNCTIONS:
    body.append('\n\n' + funcs[name])
body.append("\n\nif __name__ == '__main__':\n    raise SystemExit(main())\n")
out = '\n'.join(body)
compile(out, OUT, 'exec')
with open(OUT, 'x') as f:
    f.write(out)
print('wrote', OUT, hashlib.sha256(out.encode()).hexdigest(), len(out), 'bytes')
