FAULT = _os.environ.get('FAKE451_FAULT', '')
D = Path(_os.environ['FAKE451_D'])
ADMISSION_BYTES = 1024**2
VERIFY_FREE_BYTES = (1 << 60) if FAULT == 'need_huge' else 1024**2


class _Os:
    def __getattr__(self, name):
        return getattr(_os, name)

    @staticmethod
    def sched_getaffinity(pid):
        return set(range(16))


class _Subprocess:
    CalledProcessError = _subprocess.CalledProcessError
    PIPE, STDOUT = _subprocess.PIPE, _subprocess.STDOUT

    @staticmethod
    def run(argv, *a, **k):
        argv = [str(x) for x in argv]
        if argv[0] == '/usr/bin/python3':
            argv[0] = sys.executable
        return _subprocess.run(argv, *a, **k)


os = _Os()
subprocess = _Subprocess()
''' % (REAL_SHA[:12], ', '.join(KEEP_FUNCTIONS), ', '.join(KEEP_CONSTANTS))

stubs = '''

