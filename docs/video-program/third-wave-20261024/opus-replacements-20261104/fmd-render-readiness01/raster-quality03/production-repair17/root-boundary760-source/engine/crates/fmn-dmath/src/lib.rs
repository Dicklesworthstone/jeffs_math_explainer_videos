/// `sqrt` — delegated to the hardware instruction on purpose: IEEE 754
/// requires correct rounding, so it is bit-identical on every certified
/// target already. Max error: 0.5 ulp (correctly rounded).
#[must_use]
pub fn sqrt(x: f64) -> f64 {
    x.sqrt()
}

/// Apply the certified [`sqrt`] definition to a slice in place.
///
/// Independent values are grouped into build-tier SIMD lanes; every output
/// is bit-identical to calling [`sqrt`] on that element. The scalar tail
/// preserves the same definition for lengths not divisible by the lane
/// count.
pub fn sqrt_slice(values: &mut [f64]) {
    use std::simd::StdFloat as _;

    let mut index = 0;
    while index + bits::SIMD_LANES <= values.len() {
        let roots = bits::F64x::from_slice(&values[index..]).sqrt();
        roots.copy_to_slice(&mut values[index..index + bits::SIMD_LANES]);
        index += bits::SIMD_LANES;
    }
    for value in &mut values[index..] {
        *value = sqrt(*value);
    }
}

/// The standard/certified seam (§6.6): one function table, chosen at
/// engine construction. `certified` construction takes [`CERTIFIED`];
/// `standard` may take [`FAST`]. Call sites hold the table, never a cfg.
#[derive(Clone, Copy)]
pub struct Transcendentals {
    pub sin: fn(f64) -> f64,
    pub cos: fn(f64) -> f64,
    pub tan: fn(f64) -> f64,
    pub asin: fn(f64) -> f64,
    pub acos: fn(f64) -> f64,
    pub atan: fn(f64) -> f64,
    pub atan2: fn(f64, f64) -> f64,
    pub exp: fn(f64) -> f64,
    pub ln: fn(f64) -> f64,
    pub log2: fn(f64) -> f64,
    pub pow: fn(f64, f64) -> f64,
    pub powi: fn(f64, i32) -> f64,
    pub sqrt: fn(f64) -> f64,
    pub cbrt: fn(f64) -> f64,
    pub sinh: fn(f64) -> f64,
    pub cosh: fn(f64) -> f64,
    pub tanh: fn(f64) -> f64,
}

/// The certified table: fmn-dmath exclusively. This is the definition the
/// certified engine's bits are a function of.
pub const CERTIFIED: Transcendentals = Transcendentals {
    sin,
    cos,
    tan,
    asin,
    acos,
    atan,
    atan2,
    exp,
    ln,
    log2,
    pow,
    powi,
    sqrt,
    cbrt,
    sinh,
    cosh,
    tanh,
};

/// The fast table: platform libm via `std`. Deterministic per
/// build/platform only — `standard` mode, always labeled, never certified.
pub const FAST: Transcendentals = Transcendentals {
    sin: f64::sin,
    cos: f64::cos,
    tan: f64::tan,
    asin: f64::asin,
    acos: f64::acos,
    atan: f64::atan,
    atan2: f64::atan2,
    exp: f64::exp,
    ln: f64::ln,
    log2: f64::log2,
    pow: f64::powf,
    powi: f64::powi,
    sqrt,
    cbrt: f64::cbrt,
    sinh: f64::sinh,
    cosh: f64::cosh,
    tanh: f64::tanh,
};

