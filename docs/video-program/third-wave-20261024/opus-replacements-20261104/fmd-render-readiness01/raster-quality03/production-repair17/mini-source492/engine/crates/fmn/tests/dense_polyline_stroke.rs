//! GH #1: a dense `set_points_as_corners` polyline — the reporter's own
//! 288-vertex random walk, stroked 7 wide at 1280×720 — renders as one
//! unbroken line through the public scene-to-PNG path.
//!
//! The corner construction puts every handle at its chord's midpoint, and
//! point storage rounds it an ulp off the line. That left the nearest-point
//! cubic ill-conditioned: segments longer than the stroke is wide lost their
//! interior and rendered with gaps. The measure is the reporter's: walk the
//! true centerline at quarter-pixel steps and require ink within one pixel.

