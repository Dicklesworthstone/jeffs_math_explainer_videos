fn walk(y0: f64) -> Vec<Vec3> {
    let last = (WALK.len() - 1) as f64;
    WALK.iter()
        .enumerate()
        .map(|(i, y)| [-5.5 + 11.0 * i as f64 / last, y0 + y, 0.0])
        .collect()
}

/// `VMobject.set_points_as_corners`: anchors with midpoint handles, and no
/// semantic line hint (the Python surface's route, unlike `polyline`).
fn corners(vertices: &[Vec3]) -> Vec<Vec3> {
    let mut points = vec![vertices[0]];
    for pair in vertices.windows(2) {
        let [a, b] = [pair[0], pair[1]];
        points.push([
            (a[0] + b[0]) / 2.0,
            (a[1] + b[1]) / 2.0,
            (a[2] + b[2]) / 2.0,
        ]);
        points.push(b);
    }
    points
}

struct DensePolyline;

impl SceneConstruct for DensePolyline {
    fn construct(&mut self, stage: &mut Stage<'_>) -> fmn::Result<()> {
        let style = Style::default().stroke(WHITE, 7.0, 1.0);
        stage.add(VMobject::from_points(corners(&walk(2.2))).with_style(style))?;
        stage.add(VMobject::from_points(corners(&walk(-0.3))).with_style(style))?;
        Ok(())
    }
}

fn to_pixel(p: Vec3) -> [f64; 2] {
    let frame_width = FRAME_HEIGHT * f64::from(WIDTH) / f64::from(HEIGHT);
    [
        (p[0] + frame_width / 2.0) / frame_width * f64::from(WIDTH),
        (FRAME_HEIGHT / 2.0 - p[1]) / FRAME_HEIGHT * f64::from(HEIGHT),
    ]
}

/// Centerline samples (quarter-pixel steps) with no ink within one pixel,
/// ignoring samples within 4 px of the frame edge. Returns (inside, gaps).
fn uncovered(image: &fmn_codec::DecodedPng, vertices: &[Vec3]) -> (usize, Vec<[f64; 2]>) {
    let width = image.width as usize;
    let luminance = |x: usize, y: usize| image.rgba[(y * width + x) * 4];
    let mut inside = 0;
    let mut gaps = Vec::new();
    for pair in vertices.windows(2) {
        let (a, b) = (to_pixel(pair[0]), to_pixel(pair[1]));
        let length = ((b[0] - a[0]).powi(2) + (b[1] - a[1]).powi(2)).sqrt();
        let steps = ((length / 0.25) as usize).max(1);
        for k in 0..steps {
            let t = k as f64 / steps as f64;
            let x = (a[0] + (b[0] - a[0]) * t).round() as i64;
            let y = (a[1] + (b[1] - a[1]) * t).round() as i64;
            if x < 4 || y < 4 || x >= i64::from(WIDTH) - 4 || y >= i64::from(HEIGHT) - 4 {
                continue;
            }
            inside += 1;
            let (x, y) = (x as usize, y as usize);
            let ink = (y - 1..=y + 1)
                .flat_map(|row| (x - 1..=x + 1).map(move |col| (col, row)))
                .map(|(col, row)| luminance(col, row))
                .max()
                .unwrap_or(0);
            if ink < 128 {
                gaps.push([x as f64, y as f64]);
            }
        }
    }
    (inside, gaps)
}

#[test]
fn a_dense_corner_polyline_renders_without_gaps() {
    let mut options = RenderOptions::new("/dense").expect("bundled defaults");
    options.format = RenderFormat::PngSequence;
    options.config.camera.resolution = (WIDTH, HEIGHT);
    options.config.sizes.frame_height = FRAME_HEIGHT;
    options.config.determinism.mode = DeterminismMode::Certified;
    options.config.render.threads = ThreadPolicy::Fixed(4);
    let fs = Arc::new(VirtualFs::new());
    let report =
        render_with_fs(&mut DensePolyline, options, fs.clone()).expect("static scene exports");
    assert_eq!(report.artifact.frame_count, 1);
    let image = decode_png(
        &fs.read(Path::new("/dense/frame_000000.png"))
            .expect("published PNG"),
        &PngLimits::default(),
    )
    .expect("native PNG decodes");
    assert_eq!((image.width, image.height), (WIDTH, HEIGHT));
    for (label, y0) in [("raw", 2.2), ("lower", -0.3)] {
        let (inside, gaps) = uncovered(&image, &walk(y0));
        assert!(inside > 5_000, "{label}: only {inside} samples in frame");
        assert!(
            gaps.is_empty(),
            "{label}: {} of {inside} centerline samples uncovered, first at {:?}",
            gaps.len(),
            gaps.first()
        );
    }
}
