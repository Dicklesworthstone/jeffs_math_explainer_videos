/// Relative error of the quadratic circle model's arc length against the
/// analytic circumference: `|L − 2πr| / (2πr)` for the full-circle
/// [`QuadPath::try_arc`] at `radius`.
///
/// The model is sixteen quadratic Béziers standing in for the circle (the
/// BN-09 density rule), so this error is *not* rounding — it is the
/// approximation shortfall of the model itself, and the test's tolerance
/// is a property of the model, pinned against regression. Measured:
/// 1.006e-4 relative, independent of radius.
#[must_use]
pub fn circle_arc_length_rel_error(radius: f64) -> f64 {
    let path = QuadPath::try_arc(0.0, TAU, radius, [0.0; 3], None)
        .expect("the oracle's fixed full-turn component request is valid");
    let measured = ArcLengthTable::for_path(&path).total();
    let analytic = TAU * radius.abs();
    if analytic == 0.0 {
        return 0.0;
    }
    (measured - analytic).abs() / analytic
}

/// Nodes and weights for 3-point Gauss–Legendre quadrature on `[0, 1]`
/// (exact for polynomials through degree 5; the integrand here — the norm
/// of a linear vector — is smooth, so panels converge fast).
const GL3: [(f64, f64); 3] = [
    (0.5 - 0.5 * 0.774_596_669_241_483, 5.0 / 9.0),
    (0.5, 8.0 / 9.0),
    (0.5 + 0.5 * 0.774_596_669_241_483, 5.0 / 9.0),
];

/// The speed `|B'(t)|` of one quadratic, the quadrature integrand. This is
/// an *independent* evaluation: [`quadratic_arc_length`] integrates a
/// closed-form antiderivative, this samples the derivative directly.
fn quadratic_speed(a0: Vec3, h: Vec3, a1: Vec3, t: f64) -> f64 {
    let d = [
        2.0 * ((1.0 - t) * (h[0] - a0[0]) + t * (a1[0] - h[0])),
        2.0 * ((1.0 - t) * (h[1] - a0[1]) + t * (a1[1] - h[1])),
        2.0 * ((1.0 - t) * (h[2] - a0[2]) + t * (a1[2] - h[2])),
    ];
    (d[0] * d[0] + d[1] * d[1] + d[2] * d[2]).sqrt()
}

/// Composite 3-point Gauss–Legendre integral of the quadratic's speed
/// over `panels` equal panels. Monotonic in accuracy; deterministic.
fn quadrature_arc_length(a0: Vec3, h: Vec3, a1: Vec3, panels: usize) -> f64 {
    let panels = panels.max(1);
    let width = 1.0 / panels as f64;
    let mut total = 0.0;
    for panel in 0..panels {
        let base = panel as f64 * width;
        for (node, weight) in GL3 {
            total += weight * quadratic_speed(a0, h, a1, base + node * width);
        }
    }
    total * width * 0.5
}

/// Absolute error of the closed-form [`quadratic_arc_length`] against an
/// independent Gauss–Legendre integral of the same curve's speed, at
/// `panels` panels. This is the quadratic-Bézier row of the taxonomy: the
/// two computations share no code path (one evaluates an antiderivative
/// with a logarithm; the other samples the derivative), so agreement is
/// evidence for the closed form, not for a common mistake.
#[must_use]
pub fn quadratic_arc_length_vs_quadrature(a0: Vec3, h: Vec3, a1: Vec3, panels: usize) -> f64 {
    let closed = quadratic_arc_length(a0, h, a1);
    let numeric = quadrature_arc_length(a0, h, a1, panels);
    (closed - numeric).abs()
}

/// Relative error of a whole path's [`ArcLengthTable`] total against the
/// same independent quadrature summed curve by curve, at `panels` panels
/// per curve.
///
/// This is the ellipse row: an ellipse-shaped quadratic model (a circle
/// model under a non-uniform scale) has no elementary circumference, so
/// the analytic reference for the *model's* length is a high-precision
/// integral, and computing it by a different method keeps the check
/// honest. Returns 0.0 for an empty path.
#[must_use]
pub fn path_arc_length_vs_quadrature(path: &QuadPath, panels: usize) -> f64 {
    let closed = ArcLengthTable::for_path(path).total();
    if closed == 0.0 {
        return 0.0;
    }
    let numeric: f64 = path
        .bezier_tuples()
        .map(|[a0, h, a1]| quadrature_arc_length(a0, h, a1, panels))
        .sum();
    (closed - numeric).abs() / closed
}

