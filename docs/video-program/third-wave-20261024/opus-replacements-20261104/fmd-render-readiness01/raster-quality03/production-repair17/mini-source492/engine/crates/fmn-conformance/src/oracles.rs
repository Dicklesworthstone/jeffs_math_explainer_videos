/// The winding number of the closed polyline `points` about `query`
/// (xy-plane). [`get_winding_number`] winds about the origin; translating
/// the polyline by `−query` recenters it.
#[must_use]
pub fn winding_number_about(points: &[Vec3], query: Vec3) -> f64 {
    let recentered: Vec<Vec3> = points
        .iter()
        .map(|p| [p[0] - query[0], p[1] - query[1], p[2] - query[2]])
        .collect();
    get_winding_number(&recentered)
}

/// Maximum deviation from integer invariance under integer translations:
/// for each `(polygon, query, translation)` triple this compares
/// `w(P about q)` against `w(P+t about q+t)` — the winding number is a
/// translation-covariant quantity, so the two must agree to rounding.
/// Returns the largest discrepancy found; ~1e-15 in practice.
#[must_use]
pub fn winding_translation_max_error(
    polygons: &[&[Vec3]],
    queries: &[Vec3],
    translations: &[Vec3],
) -> f64 {
    let mut worst = 0.0f64;
    for &polygon in polygons {
        for &query in queries {
            let base = winding_number_about(polygon, query);
            for &t in translations {
                let shifted: Vec<Vec3> = polygon
                    .iter()
                    .map(|p| [p[0] + t[0], p[1] + t[1], p[2] + t[2]])
                    .collect();
                let moved = winding_number_about(
                    &shifted,
                    [query[0] + t[0], query[1] + t[1], query[2] + t[2]],
                );
                worst = worst.max((base - moved).abs());
            }
        }
    }
    worst
}

/// One probe of a nested-containment winding measurement.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct WindingProbe {
    /// The probe point (xy).
    pub query: Vec3,
    /// The winding number the contours produce there, as measured.
    pub measured: f64,
    /// The exact integer the geometry dictates.
    pub expected: i64,
}

/// Error of one probe: `|measured − expected|`.
#[must_use]
pub fn winding_probe_error(probe: &WindingProbe) -> f64 {
    (probe.measured - probe.expected as f64).abs()
}

/// Measure the winding number of `contours` (each a closed polyline) at
/// `query`: the sum of the per-contour winding numbers. Nested opposite-
/// wound contours cancel (a hole reads 0); nested same-wound contours
/// accumulate (a doubly-wound region reads ±2) — the parity difference
/// the fill rules key on.
#[must_use]
pub fn probe_winding(contours: &[&[Vec3]], query: Vec3) -> WindingProbe {
    let measured: f64 = contours
        .iter()
        .map(|c| winding_number_about(c, query))
        .sum();
    WindingProbe {
        query,
        measured,
        expected: measured.round() as i64,
    }
}

/// Largest probe error over a set, the number a test asserts small.
#[must_use]
pub fn winding_probes_max_error(probes: &[WindingProbe]) -> f64 {
    probes.iter().map(winding_probe_error).fold(0.0, f64::max)
}

