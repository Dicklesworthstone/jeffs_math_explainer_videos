//! Correctness oracles (§16.3 plane 1, fm-t1v).
//!
//! §16.3 names three test planes; this module is plane 1's machinery. Its
//! layout follows §16.3's own taxonomy for the plane — every oracle below
//! is filed under exactly one of these rows, and the integration tests in
//! `tests/oracles.rs` assert each measured error against its tolerance:
//!
//! 1. **Analytic ground truths.**
//!    - *Arc length vs closed forms* — [`circle_arc_length_rel_error`]
//!      (quadratic circle model vs the analytic circumference),
//!      [`quadratic_arc_length_vs_quadrature`] and
//!      [`path_arc_length_vs_quadrature`] (the closed form of
//!      `fmn_geom::arclength` vs an independent Gauss–Legendre integral —
//!      the ellipse case: a scaled circle model has no elementary
//!      circumference, so the honest reference is a high-precision
//!      integral of the model itself, computed by a *different* method).
//!    - *Path-boolean identities* — [`boolean_union_commutes_area_error`],
//!      [`boolean_partition_area_error`], [`boolean_de_morgan_area_error`].
//!    - *Winding invariants* — [`winding_translation_max_error`] (integer
//!      translations preserve winding numbers), [`probe_winding`] and
//!      [`winding_probes_max_error`] (nested containment: the number of
//!      signed turns at a probe, whose parity each fill rule reads
//!      differently — the tests assert the per-rule filledness flips).
//!    - *Color-model round-trips* — the sRGB transfer functions live in
//!      `fmn-frame`, a deliberate dev-only edge of this crate, so the
//!      round-trip measurement (`srgb_decode ∘ srgb_encode`, and the full
//!      byte → decode → encode → byte pipeline) is an oracle *test* in
//!      `tests/oracles.rs`, not a function here.
//!    - *TeX Appendix-G placement parameters* — [`tex_appendix_g_errors`]
//!      measures the remaining taxonomy rows through the pinned fmd-math
//!      engine: the σ₁₃/σ₁₄/σ₁₅ superscript shifts, the σ₁₆ subscript
//!      shift, rule 18's 4θ script separation, and rule 11's radical
//!      overbar. The axis-centered fraction bar (σ₂₂, ξ₈) is already
//!      pinned by `fmn-tex/tests/fmd_math_surface.rs`
//!      (`typeset_produces_placed_output_through_the_pin`) and is not
//!      duplicated here; the pin's own upstream suite covers the full
//!      parameter family, but that suite does not run in this repo's CI,
//!      which is what this oracle is for.
//!
//! 2. **Metamorphic laws, restricted to valid laws.**
//!    - *Integer-pixel translation equivariance* — a frame-level law; it
//!      lives with the other frame-level assertions in `tests/oracles.rs`
//!      (same dev-only `fmn-frame` edge as the color oracles). Its domain
//!      boundary, found by measurement, is documented on the test.
//!    - *Stateless resampling* — [`stateless_resampling_max_error`]:
//!      resampling a path at a second density (uniform subdivision) and
//!      evaluating both densities at common arc-length parameters yields
//!      points that lie on the original curve.
//!    - *Subdivision invariance* — [`boolean_subdivision_area_error`]:
//!      boolean results are invariant under path resampling. The valid
//!      domain is *area* agreement within a tolerance that scales with
//!      the flattening bound — see the function's docs for the boundary.
//!
//! 3. **Structural fixtures against the Reference** (§16.4's loose
//!    tolerances, since we compute in f64 over the same formulas).
//!    [`FixtureCorpus`] builds on [`crate::npy`] to load the
//!    `fixtures/npy` corpus with manifest-hash verification. The corpus
//!    rows and who compares them:
//!    - *constructor point arrays* (arc component arrays) and *positional
//!      API results* (partial-curve extraction, parameter evaluation, the
//!      integer/residue curve walk) — this module's tests, exercising the
//!      rows added with this bead (`arc_half_n8`, `partial_quad_*`,
//!      `quad_eval`, `integer_interpolate`).
//!    - *family shapes* (Polygon, Rectangle, Line, Circle, Arc, Ellipse,
//!      RegularPolygon point arrays) — already locked against the
//!      Reference by `fmn-library/tests/geometry_parity.rs` (30 cases,
//!      generated by `scripts/gen_geometry_fixtures.py`), so they are not
//!      re-fixed here; duplicating them would only assert the same
//!      formulas twice.
//!    - `point_from_proportion` positional results are deliberately *not*
//!      fixture-compatible: our proportion layer is true arc length
//!      (fm-xci, BN-03) where the Reference's is a chord heuristic, so
//!      there is no coincident formula to fixture.
//!
//! Every function here returns its **measured error** (or the measurement
//! record) rather than asserting: the library stays panic-free and the
//! test target owns the pass/fail bar, per this crate's doctrine.

