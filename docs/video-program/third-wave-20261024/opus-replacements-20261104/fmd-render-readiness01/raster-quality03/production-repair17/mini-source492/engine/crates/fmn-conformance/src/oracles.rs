// 2. Metamorphic laws — stateless resampling, subdivision invariance
// =====================================================================

/// The stateless-resampling law: clone `path`, subdivide every curve into
/// `inserts + 1` sub-curves ([`QuadPath::insert_n_curves`]), then at each
/// arc-length fraction in `alphas` evaluate the **resampled** path and
/// measure how far that point lies off the **original** curve (minimum
/// distance to any of the original's quadratics, via
/// [`distance_to_quadratic`]). Returns the worst such distance.
///
/// The law's domain: subdivision of a quadratic at a parameter is exact
/// up to rounding (de Casteljau), so the resampled path traces the same
/// geometric curve and this error is ~1e-12 for order-one geometry. It is
/// *not* claimed for arc-length fractions below the table's inversion
/// accuracy on degenerate (zero-length or cusp) curves — the probes in
/// `alphas` stay interior for that reason.
#[must_use]
pub fn stateless_resampling_max_error(path: &QuadPath, inserts: usize, alphas: &[f64]) -> f64 {
    let mut resampled = path.clone();
    let _ = resampled.insert_n_curves(inserts);
    let table = ArcLengthTable::for_path(&resampled);
    let original_curves: Vec<[Vec3; 3]> = path.bezier_tuples().collect();
    let mut worst = 0.0f64;
    for &alpha in alphas {
        let Some((curve, t)) = table.curve_and_t_at(&resampled, alpha) else {
            continue;
        };
        let Some(point) = resampled.nth_curve_point(curve, t) else {
            continue;
        };
        let distance = original_curves
            .iter()
            .map(|[a0, h, a1]| distance_to_quadratic(*a0, *h, *a1, point))
            .fold(f64::INFINITY, f64::min);
        worst = worst.max(distance);
    }
    worst
}

/// The subdivision-invariance law for booleans: `|area(op(A, B)) −
/// area(op(A′, B))|` where `A′` is `A` resampled by
/// [`QuadPath::insert_n_curves`].
///
/// The valid domain is **area agreement within flatten-induced drift**:
/// the certified boolean flattens curves to `options.tolerance` before
/// clipping, and resampling moves the flattening's segment boundaries, so
/// two flattenings of the same curve may differ by O(perimeter ×
/// tolerance) in area. Bit-level output equality is *not* a valid law
/// here — the arrangement legitimately differs at its own rounding scale.
/// On the probe scene (unit-circle subject, polygonal clip, scene
/// tolerance) the measured drift is exactly 0.0 for union, intersection,
/// and difference: the deterministic flatten reproduces the same chords
/// under uniform subdivision. The test pins a small bound rather than
/// exact zero so the law does not overclaim beyond its probe.
///
/// # Errors
/// [`OracleError::Boolean`] if an evaluation refuses its inputs.
pub fn boolean_subdivision_area_error(
    a: &QuadPath,
    b: &QuadPath,
    operation: BooleanOperation,
    inserts: usize,
    options: BooleanOptions,
) -> Result<f64, OracleError> {
    let mut resampled = a.clone();
    let _ = resampled.insert_n_curves(inserts);
    let base = boolean_area(a, b, operation, options)?;
    let subdivided = boolean_area(&resampled, b, operation, options)?;
    Ok((base - subdivided).abs())
}

