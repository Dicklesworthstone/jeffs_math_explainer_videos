/// The measured Appendix-G placement errors (in ems) for the taxonomy
/// rows not already pinned by `fmn-tex`'s surface test. Every field is an
/// absolute error against the published Computer Modern parameter
/// ([`fmd_math::metrics::CM`]), except `script_separation_over_4theta`,
/// which is a clearance margin: `(sup_y − sub_y) − 4θ`, required to be
/// **positive** by rule 18 rather than near zero.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct TexAppendixG {
    /// σ₁₃: display-style uncramped superscript shift (`x^2`, Display).
    pub display_superscript_shift: f64,
    /// σ₁₄: non-display uncramped superscript shift (`x^2`, Text).
    pub text_superscript_shift: f64,
    /// σ₁₅: cramped superscript shift (`\sqrt{x^2}`, Display).
    pub cramped_superscript_shift: f64,
    /// σ₁₆: lone subscript shift (`x_i`, Display).
    pub lone_subscript_shift: f64,
    /// Rule 18 margin for `x_i^2` in Display: the measured
    /// superscript-to-subscript separation minus 4θ. Valid when positive.
    pub script_separation_over_4theta: f64,
    /// ξ₈: the radical overbar's thickness (`\sqrt{x}`, Display).
    pub radical_rule_thickness: f64,
    /// Rule 11 margin: the clearance between the `\sqrt{x}` overbar and
    /// the radicand's height minus ψ (θ + x-height/4). Valid when
    /// positive (CM's surd overshoots, so this is strictly positive).
    pub radical_clearance_over_psi: f64,
}

/// Measure the Appendix-G rows through the pinned fmd-math engine at its
/// published CM constants. Cases are chosen so the clearance terms of the
/// rules do not bind (short glyphs, display style), making the published
/// parameter the exact expected coordinate — the same discipline as the
/// pin's upstream placement suite, asserted here so a SUITE.lock bump
/// that drifted placement fails in *this* repo's CI.
///
/// # Errors
/// [`OracleError::Tex`] if the bundled faces fail to load or a probe
/// source fails to typeset.
pub fn tex_appendix_g_errors() -> Result<TexAppendixG, OracleError> {
    use fmd_math::Style;

    let engine = fmd_math::Engine::bundled().map_err(|e| OracleError::Tex(e.to_string()))?;
    let c = engine.constants();
    let typeset = |src: &str, style: Style| {
        engine
            .typeset(src, style)
            .map_err(|e| OracleError::Tex(format!("{src:?}: {e}")))
    };
    let glyph_y = |layout: &fmd_math::Layout, ch: char, src: &str| {
        layout
            .glyphs
            .iter()
            .find(|g| g.ch == ch)
            .map(|g| g.y)
            .ok_or_else(|| OracleError::Tex(format!("{src:?}: no {ch:?} glyph")))
    };

    let display_scripts = typeset("x^2", Style::Display)?;
    let text_scripts = typeset("x^2", Style::Text)?;
    let cramped = typeset(r"\sqrt{x^2}", Style::Display)?;
    let lone_sub = typeset("x_i", Style::Display)?;
    let both = typeset("x_i^2", Style::Display)?;
    let radicand = typeset("x", Style::Display)?;
    let radical = typeset(r"\sqrt{x}", Style::Display)?;

    let rule = radical
        .rules
        .first()
        .ok_or_else(|| OracleError::Tex(r"\sqrt{x}: no overbar rule".to_string()))?;
    let psi = c.rule_thickness + 0.25 * c.x_height;

    Ok(TexAppendixG {
        display_superscript_shift: (glyph_y(&display_scripts, '2', "x^2")? - c.sup1).abs(),
        text_superscript_shift: (glyph_y(&text_scripts, '2', "x^2")? - c.sup2).abs(),
        cramped_superscript_shift: (glyph_y(&cramped, '2', r"\sqrt{x^2}")? - c.sup3).abs(),
        lone_subscript_shift: (glyph_y(&lone_sub, 'i', "x_i")? + c.sub1).abs(),
        script_separation_over_4theta: (glyph_y(&both, '2', "x_i^2")?
            - glyph_y(&both, 'i', "x_i^2")?)
            - 4.0 * c.rule_thickness,
        radical_rule_thickness: (rule.height - c.rule_thickness).abs(),
        radical_clearance_over_psi: (rule.y - radicand.height) - psi,
    })
}

