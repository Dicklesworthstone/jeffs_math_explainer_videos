/// A failure to produce an oracle measurement (distinct from a measurement
/// that exceeds its tolerance — that is the test's call, not this type's).
#[derive(Debug)]
pub enum OracleError {
    /// A path boolean refused or exhausted a budget.
    Boolean(BooleanError),
    /// A geometry constructor refused its inputs.
    Geom(String),
    /// The TeX engine's bundled faces failed to load, or a typeset call
    /// refused the probe source.
    Tex(String),
    /// A fixture row was missing, corrupt, or shaped wrong.
    Fixture(String),
}

impl fmt::Display for OracleError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Boolean(e) => write!(f, "boolean oracle input refused: {e}"),
            Self::Geom(e) => write!(f, "geometry oracle input refused: {e}"),
            Self::Tex(e) => write!(f, "TeX oracle failed to produce a layout: {e}"),
            Self::Fixture(e) => write!(f, "fixture corpus: {e}"),
        }
    }
}

impl std::error::Error for OracleError {}

impl From<BooleanError> for OracleError {
    fn from(e: BooleanError) -> Self {
        Self::Boolean(e)
    }
}

