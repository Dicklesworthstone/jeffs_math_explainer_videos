def clip(polygon, a, b, c):
    """Keep the part of a convex polygon where a x + b y <= c (Sutherland and Hodgman)."""
    out = []
    for i, p in enumerate(polygon):
        q = polygon[(i + 1) % len(polygon)]
        sp, sq = a * p[0] + b * p[1] - c, a * q[0] + b * q[1] - c
        if sp <= 0:
            out.append(p)
        if (sp < 0 < sq) or (sq < 0 < sp):
            t = sp / (sp - sq)
            out.append((p[0] + t * (q[0] - p[0]), p[1] + t * (q[1] - p[1])))
    return out


def factory():
    emit("K-L1.limits", join((f"{a},{b},{c}" for _, a, b, c in LIMITS), ";"))
    emit("K-L1.profit", join(PROFIT))
