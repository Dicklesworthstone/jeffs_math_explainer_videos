    for _, a, b, c in LIMITS:
        polygon = clip(polygon, F(a), F(b), F(c))
    corners = sorted(set(polygon))
    emit("K-L2.corners", join((f"{frac(x)},{frac(y)}" for x, y in corners), ";"))
    profit = lambda p: PROFIT[0] * p[0] + PROFIT[1] * p[1]
    emit("K-L2.profits", join(frac(profit(p)) for p in corners))
    best = max(corners, key=profit)
    emit("K-L2.best", f"{frac(best[0])},{frac(best[1])}")
    emit("K-L2.best_profit", frac(profit(best)))
    emit("K-L2.tight", join(name for name, a, b, c in LIMITS if a * best[0] + b * best[1] == c))
    stray = (0, 60)
    emit("K-L2.not_a_corner", join(stray))
    allowed = lambda x, y: x >= 0 and y >= 0 and all(a * x + b * y <= c for _, a, b, c in LIMITS)
    emit("K-L2.not_a_corner_allowed", allowed(*stray))
    emit("K-L2.not_a_corner_breaks", join(name for name, a, b, c in LIMITS if a * stray[0] + b * stray[1] > c))
    plans = [(x, y) for x in range(101) for y in range(101) if allowed(x, y)]
    best_plan = max(plans, key=profit)
    emit_later["K-X5.plans"] = len(plans)
    emit_later["K-X5.best_plan"] = join(best_plan)
    emit_later["K-X5.best_is_a_corner"] = profit(best_plan) == profit(best)
    return {"best": f"{frac(best[0])},{frac(best[1])}", "best_profit": frac(profit(best))}


