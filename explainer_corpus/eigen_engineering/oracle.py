def uses(c, x):
    return [c[0][0] * x[0] + c[0][1] * x[1], c[1][0] * x[0] + c[1][1] * x[1]]


def eigen_fractions(c):
    """Eigenvalues from LAPACK, turned into fractions and verified exactly; largest first."""
    values = sorted((F(float(x)).limit_denominator(10**6) for x in np.linalg.eigvals(np.array(c, float)).real),
                    reverse=True)
    for lam in values:
        assert (c[0][0] - lam) * (c[1][1] - lam) - c[0][1] * c[1][0] == 0, f"{lam} is not an eigenvalue"
    return values


def eigenvector(c, lam):
    """The smallest whole numbers (x, y), x > 0, with C (x, y) = lam (x, y), by search."""
    for x in range(1, 50):
        for y in range(-50, 51):
            if uses(c, [F(x), F(y)]) == [lam * x, lam * y] and math.gcd(x, abs(y)) == 1:
                return [x, y]
    raise SystemExit("oracle: no small whole eigenvector")


def inverse(c):
    m = [[1 - c[0][0], -c[0][1]], [-c[1][0], 1 - c[1][1]]]
    det = m[0][0] * m[1][1] - m[0][1] * m[1][0]
    if det == 0:
        return None
    return [[m[1][1] / det, -m[0][1] / det], [-m[1][0] / det, m[0][0] / det]]


def feeds_itself(c):
    inv = inverse(c)
    return inv is not None and all(x >= 0 for row in inv for x in row)


def hawkins_simon(c):
    return 1 - c[0][0] > 0 and (1 - c[0][0]) * (1 - c[1][1]) - c[0][1] * c[1][0] > 0


def rounds(c, d, n):
    out = [list(d)]
    for _ in range(n):
        out.append(uses(c, out[-1]))
    return out


