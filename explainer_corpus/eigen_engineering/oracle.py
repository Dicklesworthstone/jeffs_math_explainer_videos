#!/usr/bin/env python3
"""Facts oracle for Video K, "The One Idea Behind Bridges, Concert Halls and Economies".

Run from this folder (`./x eigen_engineering facts-check` does):

    uv run --no-project --with numpy python3 -I -B oracle.py

stdout: one `KEY<TAB>VALUE` line per fact, the same keys `eigen facts`
prints (src/facts.rs), in the rows of docs/fact-sheet.md: K-B (the two
bridges), K-A (two carts), K-T, K-P and K-V (the truss: statics, patterns,
vibration), K-R, K-H and K-N (rooms, the hall, a hall cut into cells), K-E
(the economy), K-L (the factory), K-Q (the quizzes), K-X (the edges of the
always sentences) and K-S (cited).

stderr: cross-checks (lines starting with "#") and a summary; exit 1 if any
cross-check failed.

How the values are obtained, independently of the Rust model:
  * every eigenvalue and eigenvector by LAPACK through NumPy (the video's
    model.rs uses its own cyclic Jacobi rotations);
  * the truss's member forces by joint equilibrium alone (it has as many
    members as free joint directions), and its moves from each member's
    stretch by compatibility: no stiffness table is formed for the statics.
    For the eigenvalues the table is built as B' diag(k) B from the stretch
    matrix B, not member block by member block;
  * the truss's joints and members are written out one by one here, not
    generated by the model's loops;
  * the vibration modes as the eigenpairs of M^-1 K, an unsymmetric problem,
    not of M^-1/2 K M^-1/2;
  * room modes counted along the third side with an exact integer square
    root, not by testing every triple; the chain of slices by its closed
    form;
  * the hall's side view typed in as rows of characters;
  * the economy in Python Fractions: eigenvalues found in floating point,
    turned into fractions, and then verified exactly (C v = lambda v);
  * the factory's corners by clipping a large square with each limit in
    turn, not by intersecting pairs of lines;
  * how many directions a 2 by 2 rule sends back along themselves from the
    sign of its characteristic discriminant, not from a sweep;
  * the seeded tables of the edge tests regenerated with NumPy's own
    PCG64DXSM;
  * CITED literals from the sources listed in docs/fact-sheet.md.
"""
import datetime
import math
import sys
from fractions import Fraction as F

import numpy as np

_EMITTED = {}
_FAILED = []
_CHECKS = [0]


def emit(key, value):
    if key in _EMITTED:
        raise SystemExit(f"oracle: {key} emitted twice")
    if isinstance(value, (bool, np.bool_)):
        value = "true" if value else "false"
    _EMITTED[key] = str(value)
    print(f"{key}\t{value}")


def check(name, ok):
    _CHECKS[0] += 1
    if not ok:
        _FAILED.append(name)
    print(f"# {'ok  ' if ok else 'FAIL'} {name}", file=sys.stderr)


def join(items, sep=","):
    return sep.join(str(x) for x in items)


def fixed(x, places):
    """x to `places` decimals; refuses a value on a rounding edge; no minus zero."""
    y = float(x) * 10**places
    if abs(y - math.floor(y) - 0.5) < 1e-6:
        raise SystemExit(f"oracle: {x} sits on a rounding edge at {places} places")
    r = math.floor(y + 0.5) / 10**places
    if r == 0:
        r = 0.0
    return f"{r:.{places}f}"


def whole(x):
    r = round(float(x))
    if abs(float(x) - r) > 1e-9 * max(abs(float(x)), 1.0):
        raise SystemExit(f"oracle: {x} is not a whole number")
    return int(r)


def frac(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f"{x.numerator}/{x.denominator}"


def decimal(x):
    """A fraction whose denominator divides a power of ten, as a decimal."""
    x = F(x)
    for places in range(13):
        if (10**places) % x.denominator == 0:
            units = x.numerator * (10**places // x.denominator)
            sign, units = ("-" if units < 0 else ""), abs(units)
            if places == 0:
                return f"{sign}{units}"
            return f"{sign}{units // 10**places}.{units % 10**places:0{places}d}"
    raise SystemExit(f"oracle: {x} has no short decimal")


def metres(dm):
    return str(dm // 10) if dm % 10 == 0 else f"{dm // 10}.{dm % 10}"


