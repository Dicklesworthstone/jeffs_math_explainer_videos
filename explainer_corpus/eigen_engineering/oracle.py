def cells_table(rows):
    """One row and column per cell of air; +1, +1 and -1, -1 for every shared face."""
    index = {}
    for r, row in enumerate(reversed(rows)):  # from the floor up, as the model lists them
        for c, ch in enumerate(row):
            if ch == "#":
                index[(r, c)] = len(index)
    k = np.zeros((len(index), len(index)))
    for (r, c), i in index.items():
        for other in ((r + 1, c), (r, c + 1)):
            if other in index:
                j = index[other]
                k[i, i] += 1
                k[j, j] += 1
                k[i, j] -= 1
                k[j, i] -= 1
    return k


