BATHROOM, CUBE, STUDY, NARROW, HALL = (25, 16, 24), (30, 30, 30), (48, 40, 26), (61, 21, 25), (450, 230, 180)


def mode_hz(room, n):
    return SOUND / 2 * math.sqrt(sum((ni / (side / 10)) ** 2 for ni, side in zip(n, room)))


def count_below(room, hertz):
    """Modes at or below `hertz`: for every nx, ny, the largest nz by an exact square root."""
    lx, ly, lz = room
    right = (2 * hertz * lx * ly * lz) ** 2
    count = 0
    for nx in range(2 * lx * hertz // C_DM + 1):
        for ny in range(2 * ly * hertz // C_DM + 1):
            rest = right - C_DM**2 * ((nx * ly * lz) ** 2 + (ny * lx * lz) ** 2)
            if rest >= 0:
                count += math.isqrt(rest // (C_DM**2 * (lx * ly) ** 2)) + 1
    return count - 1  # still air is not a mode


def modes_below(room, hertz):
    lx, ly, lz = room
    out = []
    for nx in range(2 * lx * hertz // C_DM + 1):
        for ny in range(2 * ly * hertz // C_DM + 1):
            for nz in range(2 * lz * hertz // C_DM + 1):
                inside = C_DM**2 * ((nx * ly * lz) ** 2 + (ny * lx * lz) ** 2 + (nz * lx * ly) ** 2) \
                    <= (2 * hertz * lx * ly * lz) ** 2
                if (nx, ny, nz) != (0, 0, 0) and inside:
                    out.append(((nx, ny, nz), mode_hz(room, (nx, ny, nz))))
    return sorted(out, key=lambda m: (m[1], m[0]))


def volume(room):
    return F(room[0] * room[1] * room[2], 1000)


def schroeder(room, t60):
    return SCHROEDER * math.sqrt(float(t60 / volume(room)))


def sharing(room, hertz):
    """Modes at or below `hertz` whose frequency another mode has too (compared as floats)."""
    tones = [round(hz, 9) for _, hz in modes_below(room, hertz)]
    return sum(1 for t in tones if tones.count(t) > 1)


def lowest(room):
    modes = modes_below(room, 100)
    return modes[0][1], sum(1 for _, hz in modes if abs(hz - modes[0][1]) < 1e-9)


